  'M58.9 4.2V37.4M58.9 20.8C58.9 12.1 54.6 6.7 47.1 6.7C39.6 6.7 35.1 12.1 35.1 20.8C35.1 29.5 39.6 34.9 47.1 34.9C54.6 34.9 58.9 29.5 58.9 20.8',
