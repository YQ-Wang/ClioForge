import { writeFileSync } from 'node:fs';

// Original folded-paper silhouette. Angled paper edges, open lower ribs and
// the two guard sticks are structural; no letter is drawn over the fan.
function fan(count, compact = false) {
  const p = (angle, radius) => {
    const a = (angle * Math.PI) / 180;
    return `${(56 + radius * Math.sin(a)).toFixed(2)} ${(66 - radius * Math.cos(a)).toFixed(2)}`;
  };
  const folds = [];
  const spread = 124;
  const gap = compact ? 0.85 : 0.32;
  for (let i = 0; i < count; i++) {
    const a = -62 + (spread * i) / count + gap;
    const b = -62 + (spread * (i + 1)) / count - gap;
    const mid = (a + b) / 2;
    folds.push({
      d: `M${p(a, 57.8)}L${p(mid, 59)}L${p(b, 57.8)}L${p(b, 19)}Q${p(mid, 18.3)} ${p(a, 19)}Z`,
      opacity: 1,
    });
    if (!compact)
      folds.push({
        d: `M${p(mid, 59)}L${p(b, 57.8)}L${p(b, 19)}L${p(mid, 18.65)}Z`,
        opacity: 0.13,
        shade: true,
      });
  }
  const ribs = Array.from({ length: count - 1 }, (_, i) => {
    const a = -62 + (spread * (i + 1)) / count;
    return `M${p(a, 3.3)}L${p(a, 17.4)}`;
  }).join('');
  const guard = `M${p(-62, 59)}L${p(-62, 2.2)}Q56 67.8 ${p(62, 2.2)}L${p(62, 59)}`;
  return { folds, ribs, guard };
}

